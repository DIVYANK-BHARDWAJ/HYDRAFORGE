"""
hydraforge/worker/adapter_builder.py
Runtime adapter and CLI shim synthesizer for in-memory Python models.
Generates a zero-dependency CLI wrapper that connects the standardized
--input / --output interface to participant model classes or functions.
Executed STRICTLY inside the isolated worker container.
"""

from __future__ import annotations

import textwrap
from pathlib import Path
from typing import Optional


class AdapterBuilder:
    """Generates an in-container Python shim connecting CLI file-in/out to model callables."""

    @staticmethod
    def generate_shim_source(target_spec: str) -> str:
        """
        Synthesize the source code for hydraforge_shim.py.
        target_spec is in format 'module:function' or 'module:Class.method'.
        """
        mod_name, func_name = target_spec.split(":", 1) if ":" in target_spec else (target_spec, "predict")

        shim_code = f"""# HYDRAFORGE In-Container Runtime CLI Adapter Shim
# Auto-generated by HYDRAFORGE Worker Engine for isolated model execution.
# STRICT NON-INTERFERENCE: Participant repository source code is not modified.

import sys
import os
import json
import importlib
import argparse

# Add workspace to Python module search path
sys.path.insert(0, "/workspace")
if os.path.exists("/workspace/src"):
    sys.path.insert(0, "/workspace/src")

def main():
    parser = argparse.ArgumentParser(description="HYDRAFORGE Automated Inference Adapter")
    parser.add_argument("--input", "-i", required=True, help="Path to input benchmark cases JSON")
    parser.add_argument("--output", "-o", required=True, help="Path to write predictions JSON")
    args = parser.parse_args()

    # 1. Load input cases
    with open(args.input, "r", encoding="utf-8") as f:
        cases_data = json.load(f)

    # 2. Dynamically import participant module inside container
    try:
        mod = importlib.import_module("{mod_name}")
    except Exception as e:
        sys.stderr.write(f"Failed to import participant module '{mod_name}': {{e}}\\n")
        sys.exit(101)

    # 3. Resolve target callable or class method
    target_attr = "{func_name}"
    parts = target_attr.split(".")
    obj = mod
    for part in parts:
        try:
            obj = getattr(obj, part)
        except AttributeError:
            sys.stderr.write(f"Attribute '{{part}}' not found in participant model structure.\\n")
            sys.exit(102)

    # If resolved object is a class, instantiate it
    if isinstance(obj, type):
        try:
            model_instance = obj()
            predict_fn = getattr(model_instance, "predict", model_instance)
        except Exception as e:
            sys.stderr.write(f"Failed to instantiate model class '{{obj.__name__}}': {{e}}\\n")
            sys.exit(103)
    else:
        predict_fn = obj

    # 4. Invoke inference on benchmark input cases
    predictions = []
    cases_list = cases_data if isinstance(cases_data, list) else cases_data.get("cases", [cases_data])

    for case in cases_list:
        try:
            pred_out = predict_fn(case)
        except Exception as e:
            sys.stderr.write(f"Prediction execution failed for case '{{case.get('case_id', 'unknown')}}': {{e}}\\n")
            sys.exit(104)

        if isinstance(pred_out, list):
            predictions.extend(pred_out)
        elif isinstance(pred_out, dict):
            # Check if dict already contains 'predictions' list
            if "predictions" in pred_out and isinstance(pred_out["predictions"], list):
                predictions.extend(pred_out["predictions"])
            else:
                predictions.append(pred_out)

    # 5. Write predictions to output destination
    out_dir = os.path.dirname(args.output)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)

    with open(args.output, "w", encoding="utf-8") as f:
        json.dump({{"predictions": predictions}}, f, indent=2)

    sys.exit(0)

if __name__ == "__main__":
    main()
"""
        return textwrap.dedent(shim_code)

    @classmethod
    def write_shim_to_directory(cls, dest_dir: Path, target_spec: str) -> Path:
        """Write the synthesized shim script into a designated isolated directory."""
        dest_dir = Path(dest_dir).resolve()
        dest_dir.mkdir(parents=True, exist_ok=True)
        shim_path = dest_dir / "hydraforge_shim.py"
        shim_code = cls.generate_shim_source(target_spec)
        shim_path.write_text(shim_code, encoding="utf-8")
        return shim_path

